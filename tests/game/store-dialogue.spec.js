import { test, expect } from "@playwright/test";

test("Neonboy talks to Tito and Rulo, wins the duel and unlocks the forbidden archive", async ({ page }) => {
  test.setTimeout(150_000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/discografia/");
  const shop = page.getByRole("region", { name: "Tienda de discos Neonboy" });
  const prompt = shop.locator(".record-store-nearby");
  await expect(shop).toBeVisible();
  await shop.getByRole("button", { name: "Reproducir Anubis Servant" }).click();
  const musicFrame = shop.locator(".record-store-player iframe");
  await expect(musicFrame).toHaveAttribute("src", /bjlfrB-15P4/);

  await page.keyboard.down("a");
  await expect(prompt).toContainText("Tito", { timeout: 10_000 });
  await page.keyboard.up("a");
  await page.keyboard.press("e");
  const tito = shop.getByRole("dialog", { name: /Tito/ });
  await expect(tito).toBeVisible();
  await expect(musicFrame).toHaveAttribute("src", /bjlfrB-15P4/);
  await expect(tito).toContainText("última tienda de discos");
  await tito.getByRole("button", { name: /Qué hay detrás de esa puerta/ }).click();
  await expect(tito).toContainText("disco que nunca debió grabarse");
  await page.keyboard.press("Escape");
  await expect(tito).toHaveCount(0);

  await page.keyboard.down("d");
  await page.waitForTimeout(3400);
  await page.keyboard.up("d");
  await page.keyboard.down("w");
  await expect(prompt).toContainText("Rulo", { timeout: 12_000 });
  await page.keyboard.up("w");
  await page.keyboard.press("e");
  const rulo = shop.getByRole("dialog", { name: /Rulo/ });
  await expect(rulo).toBeVisible();
  await rulo.getByRole("button", { name: /Tito me habló de un disco prohibido/ }).click();
  await rulo.getByRole("button", { name: /Acepto el duelo/ }).click();
  await rulo.getByRole("button", { name: /Por eso siempre toco sentado/ }).click();
  await expect(rulo).toContainText("Flojo, pibe");
  await rulo.getByRole("button", { name: "Reintentar el duelo" }).click();
  await rulo.getByRole("button", { name: /Ellas me tienen miedo/ }).click();
  await rulo.getByRole("button", { name: /Seguir el duelo/ }).click();
  await rulo.getByRole("button", { name: /más potencia que toda tu discografía/ }).click();
  await rulo.getByRole("button", { name: /Seguir el duelo/ }).click();
  await rulo.getByRole("button", { name: /sonido en blanco y negro/ }).click();
  await expect(rulo).toContainText("El fuego nunca muere");
  await expect(musicFrame).toHaveAttribute("src", /bjlfrB-15P4/);
  await page.keyboard.press("Escape");
  await expect(shop.locator(".record-store-quest-badge")).toContainText("DUELO GANADO");

  await page.keyboard.down("s");
  await page.waitForTimeout(3100);
  await page.keyboard.up("s");
  await page.keyboard.down("a");
  await expect(prompt).toContainText("Tito", { timeout: 12_000 });
  await page.keyboard.up("a");
  await page.keyboard.press("e");
  await tito.getByRole("button", { name: /más preguntas/ }).click();
  await tito.getByRole("button", { name: /Conozco la contraseña/ }).click();
  await expect(tito).toContainText("te doy el disco");
  await tito.getByRole("button", { name: "Abrir el Archivo Prohibido" }).click();
  await expect(shop.getByRole("dialog", { name: "Archivo Prohibido de Neonboy" })).toBeVisible();
  await expect(shop.getByRole("dialog", { name: "Archivo Prohibido de Neonboy" })).toContainText("Próximamente, una nueva grabación");
  await shop.getByRole("button", { name: "Cerrar archivo" }).click();
  await expect(shop.getByRole("button", { name: "ARCHIVO PROHIBIDO" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "ARCHIVO PROHIBIDO" })).toBeVisible();
  expect(errors).toEqual([]);
});
